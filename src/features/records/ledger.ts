/**
 * The record ledger — what we published, pinned.
 *
 * One entry per **record**: one model version (or checkpoint) as it was
 * measured and priced when we published it. A model line that ships a new
 * checkpoint gets a new entry, not an edit of the old one.
 *
 * The rules this file carries (enforced by
 * `src/features/records/__tests__/records.node.test.ts`):
 *
 *  1. **Every registry model and every leaderboard row has an entry.** A new
 *     iteration is therefore always a *new* record — a new REGISTRY id, a new
 *     LEADERBOARD id, a new release post, a new entry here.
 *  2. **Pinned values do not change silently.** `scores`, `notes` and the
 *     identity of a record are pinned; a retired record's price line is
 *     pinned too. Changing one is allowed only through a logged change
 *     (`correction` for a recording error, `remeasurement` for a new
 *     measurement of the same weights).
 *  3. **A record that supersedes another retires it.** The predecessor gets
 *     a `retiredAt` date and a non-active price row, so the line reads as a
 *     history instead of a pile of rows.
 *
 * Read `src/features/records/README.md` for the workflow, and run
 * `pnpm records:pins` to print the entries that match the live registries.
 */
